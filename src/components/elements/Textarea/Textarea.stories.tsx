import type { ComponentProps } from 'react';
import type { Meta, StoryObj } from '@storybook/react-vite';
import { useTranslation } from 'react-i18next';
import { Textarea } from './Textarea';

const meta = {
	component: Textarea,
	tags: ['autodocs'],
	args: {
		id: 'textarea',
		label: '名前',
	},
	argTypes: {
		id: {
			control: false,
		},
	},
} satisfies Meta<typeof Textarea>;

export default meta;

type Story = StoryObj<typeof meta>;

const renderTextarea = (args: ComponentProps<typeof Textarea>) => {
	const { t } = useTranslation();

	return (
		<Textarea
			{...args}
			label={
				args.label === '名前'
					? t('example.story.labels.name')
					: args.label
			}
		/>
	);
};

export const Default: Story = {
	render: renderTextarea,
};

export const Required: Story = {
	args: {
		required: true,
	},
	render: renderTextarea,
};

export const Description: Story = {
	args: {
		description: '名前を入力してください。',
	},
	render: renderTextarea,
};

export const Error: Story = {
	args: {
		error: '入力内容に誤りがあります。',
	},
	render: renderTextarea,
};

export const ReadOnly: Story = {
	args: {
		readOnly: true,
		defaultValue: '変更できないテキスト',
	},
	render: renderTextarea,
};

export const DescriptionAndError: Story = {
	args: {
		description: '名前を入力してください。',
		error: '名前は必須です。',
	},
	render: renderTextarea,
};

export const AutoGeneratedId: Story = {
	args: {
		id: undefined,
	},
	render: renderTextarea,
};